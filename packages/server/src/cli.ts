/**
 * CLI `mrcatz` (pengganti `php artisan mrcatz:make` / `mrcatz:remove`).
 *
 *   npx mrcatz make Product [--path admin] [--model product] [--table products]
 *                           [--api apps/api/src] [--web apps/web/app/pages | --no-web]
 *                           [--prisma prisma/prisma.service] [--api-base /api] [--force]
 *   npx mrcatz remove Product [--path admin] [...opsi folder sama] [--force]
 */
import { existsSync, mkdirSync, readdirSync, rmdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { createInterface } from 'node:readline/promises';
import { planScaffold, type ScaffoldOptions } from './scaffold';

const HELP = `MrCatz DataTable CLI

Usage:
  mrcatz make <Name> [options]     Generate table, controller, module (NestJS) + page (Nuxt)
  mrcatz remove <Name> [options]   Delete the files generated by "make"

Options:
  --path <dir>        Sub-folder, e.g. admin
  --model <name>      Prisma model delegate (default: camelCase name)
  --table <name>      Database table for PostgreSQL relevance (default: snake_case plural)
  --api <dir>         NestJS source folder (default: apps/api/src)
  --web <dir>         Nuxt pages folder (default: apps/web/app/pages)
  --no-web            Skip the Nuxt page
  --prisma <path>     PrismaService path inside --api (default: prisma/prisma.service)
  --api-base <url>    API prefix used by the page (default: /api)
  --force             Overwrite (make) / skip confirmation (remove)
`;

function parseArgs(argv: string[]) {
  const positional: string[] = [];
  const flags: Record<string, string | boolean> = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]!;
    if (!a.startsWith('--')) {
      positional.push(a);
      continue;
    }
    const [key, inline] = a.slice(2).split('=', 2) as [string, string | undefined];
    if (inline !== undefined) flags[key] = inline;
    else if (key === 'force' || key === 'no-web' || key === 'help') flags[key] = true;
    else flags[key] = argv[++i] ?? '';
  }
  return { positional, flags };
}

export async function run(argv: string[], cwd = process.cwd()): Promise<number> {
  const { positional, flags } = parseArgs(argv);
  const [command, name] = positional;
  if (!command || flags.help || !name || !['make', 'remove'].includes(command)) {
    console.log(HELP);
    return command && !flags.help ? 1 : 0;
  }
  const str = (k: string) => (typeof flags[k] === 'string' ? (flags[k] as string) : undefined);
  const opts: ScaffoldOptions = {
    name,
    path: str('path'),
    model: str('model'),
    table: str('table'),
    apiDir: str('api'),
    webDir: flags['no-web'] ? false : str('web'),
    prismaService: str('prisma'),
    apiBase: str('api-base'),
  };
  const files = planScaffold(opts);

  if (command === 'make') {
    const clash = files.filter((f) => existsSync(resolve(cwd, f.path)));
    if (clash.length && !flags.force) {
      console.error(`Sudah ada (pakai --force untuk menimpa):\n${clash.map((f) => `  ${f.path}`).join('\n')}`);
      return 1;
    }
    for (const f of files) {
      const abs = resolve(cwd, f.path);
      mkdirSync(dirname(abs), { recursive: true });
      writeFileSync(abs, f.content);
      console.log(`  ✓ ${f.path}`);
    }
    const Name = files[2]!.content.match(/class (\w+Module)/)?.[1];
    console.log(`\nSelesai. Daftarkan ${Name} di imports AppModule.`);
    return 0;
  }

  const existing = files.filter((f) => existsSync(resolve(cwd, f.path)));
  if (!existing.length) {
    console.log('Tidak ada file untuk dihapus.');
    return 0;
  }
  console.log(existing.map((f) => `  ${f.path}`).join('\n'));
  if (!flags.force) {
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    const answer = await rl.question(`Hapus ${existing.length} file di atas? (y/N) `);
    rl.close();
    if (!/^y(es)?$/i.test(answer.trim())) return 1;
  }
  for (const f of existing) {
    const abs = resolve(cwd, f.path);
    rmSync(abs);
    // Bersihkan folder modul yang jadi kosong.
    const dir = dirname(abs);
    if (existsSync(dir) && readdirSync(dir).length === 0) rmdirSync(dir);
    console.log(`  ✗ ${f.path}`);
  }
  return 0;
}

// Dijalankan langsung sebagai bin.
run(process.argv.slice(2)).then(
  (code) => process.exit(code),
  (e: unknown) => {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  },
);
